// Determine which logo to show based on URL
export function getLinkIconComponent(url: string) {
  if (url.includes("twitter.com") || url.includes("x.com")) return XLogo;
  if (url.includes("github.com")) return GitHubLogo;
  if (url.includes("discord")) return DiscordLogo;
  if (url.includes("telegram") || url.includes("t.me")) return TelegramLogo;
  if (url.includes("youtube.com")) return YouTubeLogo;
  if (url.includes("linkedin.com")) return LinkedInLogo;
  if (url.includes("instagram.com")) return InstagramLogo;
  if (url.includes("facebook.com") || url.includes("fb.com")) return FacebookLogo;
  return RitualLogo;
}

export function getLinkLabel(url: string): string {
  if (url.includes("twitter.com") || url.includes("x.com")) return "X";
  if (url.includes("github.com")) return "GitHub";
  if (url.includes("discord")) return "Discord";
  if (url.includes("telegram") || url.includes("t.me")) return "Telegram";
  if (url.includes("youtube.com")) return "YouTube";
  if (url.includes("linkedin.com")) return "LinkedIn";
  if (url.includes("instagram.com")) return "Instagram";
  if (url.includes("facebook.com") || url.includes("fb.com")) return "Facebook";
  // Extract domain for unknown
  try {
    return new URL(url).hostname.replace("www.", "");
  } catch {
    return "Link";
  }
}
